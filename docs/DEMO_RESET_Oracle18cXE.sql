--     - PART 5 (DML 시드 데이터)
--
--   ❌ 절대 다시 실행하면 안 되는 부분
--     - PART 1 전체(테이블스페이스 TBS_ADC/TBS_ADC_TEMP, ADC_APP/ADC_BATCH 계정, ADC_PROFILE
