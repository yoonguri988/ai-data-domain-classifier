-- A-2. IDENTITY 컬럼 채번을 처음 값으로 되돌린다.
--   Oracle의 IDENTITY 컬럼은 TRUNCATE로도 자동으로 리셋되지 않는다(PostgreSQL의
--   "TRUNCATE ... RESTART IDENTITY"에 해당하는 옵션이 없다) - ALTER TABLE ... MODIFY 로 같은
--   START WITH 값을 다시 지정해줘야 한다. 안 해줘도 시연 자체는 문제없이 돌아가지만(신청 ID가
