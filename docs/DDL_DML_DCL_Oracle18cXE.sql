    CREATED_AT      TIMESTAMP       DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT FK_ANALYSIS_JOB_DATASET FOREIGN KEY (DATASET_ID) REFERENCES ANALYSIS_DATASET(DATASET_ID),
