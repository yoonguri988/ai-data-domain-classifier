CREATE SEQUENCE SEQ_DATASET_ID START WITH 1 INCREMENT BY 1 NOCACHE;
CREATE SEQUENCE SEQ_REQUEST_NO START WITH 1 INCREMENT BY 1 NOCACHE;

CREATE TABLE ANALYSIS_DATASET (
    DATASET_ID       VARCHAR2(20)   NOT NULL,                -- 예: DS0000000001 (사람이 식별 가능한 업무키 유지)
    REQUEST_NO       VARCHAR2(20)   NOT NULL,                -- 예: REQ0000000001
    DATASET_NAME     VARCHAR2(200)  NOT NULL,
    DB_SCHEMA_NAME   VARCHAR2(100)  NOT NULL,
    TABLE_NAME       VARCHAR2(100)  NOT NULL,
    DBMS_TYPE_CODE   VARCHAR2(10)   DEFAULT 'ORA' NOT NULL,  -- ORA/MYS/MSQ/PGS ...
    DATASET_STATUS   VARCHAR2(15)   DEFAULT 'REGISTERED' NOT NULL,
    REQUESTED_BY     NUMBER         NOT NULL,
    REQUESTED_AT     TIMESTAMP      DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT PK_ANALYSIS_DATASET PRIMARY KEY (DATASET_ID),
    CONSTRAINT UQ_ANALYSIS_DATASET_REQNO UNIQUE (REQUEST_NO),
    CONSTRAINT FK_ANALYSIS_DATASET_USER FOREIGN KEY (REQUESTED_BY) REFERENCES APP_USER(USER_ID),
    CONSTRAINT CK_ANALYSIS_DATASET_STATUS CHECK (DATASET_STATUS IN ('REGISTERED', 'ANALYZING', 'ANALYZED'))
);
COMMENT ON TABLE ANALYSIS_DATASET IS 'AI 도메인 판별 대상 데이터셋(테이블 단위) 등록';

CREATE TABLE ANALYSIS_COLUMN (
    COLUMN_ID        NUMBER          GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    DATASET_ID       VARCHAR2(20)    NOT NULL,
    COLUMN_NAME      VARCHAR2(100)   NOT NULL,               -- 물리 컬럼명
    COLUMN_NAME_KO   VARCHAR2(200),                          -- 한글 논리명 (형태소분석 입력)
    COLUMN_NAME_EN   VARCHAR2(200),                          -- 영문 논리명 (토큰분리 입력)
    DATA_TYPE        VARCHAR2(30),
    DATA_LENGTH      NUMBER,
    DATA_SCALE       NUMBER,
    IS_NUMERIC_YN    CHAR(1)         DEFAULT 'N' NOT NULL,
    IS_DATE_YN       CHAR(1)         DEFAULT 'N' NOT NULL,
    IS_UNIQUE_YN     CHAR(1)         DEFAULT 'N' NOT NULL,
    CREATED_AT       TIMESTAMP       DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT FK_ANALYSIS_COLUMN_DATASET FOREIGN KEY (DATASET_ID) REFERENCES ANALYSIS_DATASET(DATASET_ID) ON DELETE CASCADE,
    CONSTRAINT UQ_ANALYSIS_COLUMN UNIQUE (DATASET_ID, COLUMN_NAME),
    CONSTRAINT CK_ANALYSIS_COLUMN_NUM  CHECK (IS_NUMERIC_YN IN ('Y', 'N')),
    CONSTRAINT CK_ANALYSIS_COLUMN_DATE CHECK (IS_DATE_YN    IN ('Y', 'N')),
    CONSTRAINT CK_ANALYSIS_COLUMN_UNQ  CHECK (IS_UNIQUE_YN  IN ('Y', 'N'))
);
COMMENT ON TABLE ANALYSIS_COLUMN IS '분석 대상 컬럼 메타데이터 (AI 판별 입력 피처)';

