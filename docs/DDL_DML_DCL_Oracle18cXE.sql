CREATE TABLE ANALYSIS_JOB (
    JOB_ID          NUMBER          GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    JOB_NAME        VARCHAR2(200)   NOT NULL,
    JOB_TYPE        VARCHAR2(20)    DEFAULT 'DOMAIN_PREDICT' NOT NULL,
