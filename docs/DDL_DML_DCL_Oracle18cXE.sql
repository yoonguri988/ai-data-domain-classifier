COMMENT ON TABLE ANALYSIS_JOB IS '분석/재판별 배치 작업 등록 (구 Quartz 등록 화면 대체)';

CREATE TABLE ANALYSIS_JOB_LOG (
    LOG_ID          NUMBER          GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    JOB_ID          NUMBER          NOT NULL,
    EXEC_STATUS     VARCHAR2(20)    DEFAULT 'READY' NOT NULL,  -- READY/RUNNING/SUCCESS/INTERNAL_ERROR/CALL_ERROR (5종 상태 유지)
    STARTED_AT      TIMESTAMP,
    ENDED_AT        TIMESTAMP,
    SUCCESS_COUNT   NUMBER          DEFAULT 0,
    FAIL_COUNT      NUMBER          DEFAULT 0,
    ERROR_MESSAGE   VARCHAR2(1000),
    EXECUTED_BY     NUMBER,
    CONSTRAINT FK_ANALYSIS_JOB_LOG_JOB  FOREIGN KEY (JOB_ID) REFERENCES ANALYSIS_JOB(JOB_ID) ON DELETE CASCADE,
    CONSTRAINT FK_ANALYSIS_JOB_LOG_USR  FOREIGN KEY (EXECUTED_BY) REFERENCES APP_USER(USER_ID),
