--================================================================================
-- PART 3. DDL 보조 : 업무키(DATASET_ID/REQUEST_NO) 자동채번 트리거
--   - 기존 레거시(EgovIdGnrService) 의 "의미있는 문자열 채번" 관례를 유지하되,
--     내부 대리키(PK)는 IDENTITY 컬럼으로 단순화한 하이브리드 전략이다.
--================================================================================

CREATE OR REPLACE TRIGGER TRG_ANALYSIS_DATASET_BI
BEFORE INSERT ON ANALYSIS_DATASET
FOR EACH ROW
BEGIN
    IF :NEW.DATASET_ID IS NULL THEN
        :NEW.DATASET_ID := 'DS' || LPAD(SEQ_DATASET_ID.NEXTVAL, 10, '0');
    END IF;
    IF :NEW.REQUEST_NO IS NULL THEN
        :NEW.REQUEST_NO := 'REQ' || LPAD(SEQ_REQUEST_NO.NEXTVAL, 10, '0');
    END IF;
END;
/


