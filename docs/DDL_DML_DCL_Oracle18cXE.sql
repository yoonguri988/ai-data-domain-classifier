--================================================================================
-- PART 1. DCL : 컨테이너 접속 / 테이블스페이스 / 사용자(스키마) / 권한
--   ※ Oracle XE 18c는 CDB(Container DB) + 단일 PDB(XEPDB1) 구조입니다.
--     반드시 PDB로 접속(alter session) 후 오브젝트를 생성해야 합니다.
--================================================================================

-- 1-1. SYS 로 접속한 상태에서 PDB 전환 (SQL*Plus / SQLcl 기준)
--   sqlplus sys/<sys_password>@localhost:1521/XE as sysdba
ALTER SESSION SET CONTAINER = XEPDB1;

-- 1-2. 전용 테이블스페이스 생성
--   XE 무료버전은 사용자 데이터 총량 12GB 제한이 있으므로 AUTOEXTEND 상한을 넉넉히 두되 무제한은 지양한다.
CREATE TABLESPACE TBS_ADC
    DATAFILE 'adc_data01.dbf' SIZE 200M
    AUTOEXTEND ON NEXT 50M MAXSIZE 4G
    LOGGING
    EXTENT MANAGEMENT LOCAL AUTOALLOCATE
    SEGMENT SPACE MANAGEMENT AUTO;

CREATE TEMPORARY TABLESPACE TBS_ADC_TEMP
    TEMPFILE 'adc_temp01.dbf' SIZE 100M
    AUTOEXTEND ON NEXT 50M MAXSIZE 1G;

-- 1-3. 애플리케이션 전용 프로파일 (비밀번호 정책)
CREATE PROFILE ADC_PROFILE LIMIT
    FAILED_LOGIN_ATTEMPTS   5
    PASSWORD_LOCK_TIME      1
    PASSWORD_LIFE_TIME      90
    PASSWORD_REUSE_TIME     365
    PASSWORD_GRACE_TIME     7
    SESSIONS_PER_USER       10
    IDLE_TIME               60;

-- 1-4. 애플리케이션 스키마(사용자) 생성 - Spring Boot(JPA/MyBatis)가 사용할 커넥션 계정
--   실제 배포시 비밀번호는 .env(spring-dotenv) 로 주입하고 이 스크립트에는 평문을 남기지 않는다.
CREATE USER ADC_APP IDENTIFIED BY "ChangeMe_1234!"
    DEFAULT TABLESPACE TBS_ADC
    TEMPORARY TABLESPACE TBS_ADC_TEMP
    PROFILE ADC_PROFILE
    QUOTA UNLIMITED ON TBS_ADC;

-- 1-5. 최소 권한 원칙(Least Privilege)에 따른 시스템 권한 부여
GRANT CREATE SESSION      TO ADC_APP;
GRANT CREATE TABLE        TO ADC_APP;
GRANT CREATE VIEW         TO ADC_APP;
GRANT CREATE SEQUENCE     TO ADC_APP;
GRANT CREATE PROCEDURE    TO ADC_APP;
GRANT CREATE TRIGGER      TO ADC_APP;
GRANT CREATE TYPE         TO ADC_APP;

-- 1-6. 읽기 전용 리포팅/대시보드용 롤 (React 대시보드, PDF 리포트 배치 등에서 사용)
CREATE ROLE ROLE_ADC_READONLY;
-- 오브젝트 생성 후 PART 4에서 GRANT SELECT ... TO ROLE_ADC_READONLY 로 부여한다.

-- 1-7. 배치/스케줄러(구 Quartz 대체) 전용 계정 - 실행 계정과 조회 계정을 분리해 감사 추적을 명확히 한다.
CREATE USER ADC_BATCH IDENTIFIED BY "ChangeMe_5678!"
    DEFAULT TABLESPACE TBS_ADC
    TEMPORARY TABLESPACE TBS_ADC_TEMP
    PROFILE ADC_PROFILE
    QUOTA 500M ON TBS_ADC;

GRANT CREATE SESSION TO ADC_BATCH;
GRANT ROLE_ADC_READONLY TO ADC_BATCH;


