CREATE TABLE STANDARD_DOMAIN_REQUEST (
    REQUEST_ID            NUMBER          GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    COLUMN_ID             NUMBER          NOT NULL,
    PROPOSED_DOMAIN_CODE  VARCHAR2(20)    NOT NULL,
    AI_SUGGESTED_YN       CHAR(1)         DEFAULT 'Y' NOT NULL, -- AI 1순위 추천을 그대로 채택했는지 여부
    REQUEST_STATUS        VARCHAR2(10)    DEFAULT 'PENDING' NOT NULL,
    REQUESTED_BY          NUMBER          NOT NULL,
    REQUESTED_AT          TIMESTAMP       DEFAULT SYSTIMESTAMP NOT NULL,
    REVIEWED_BY           NUMBER,
    REVIEWED_AT           TIMESTAMP,
    REJECT_REASON         VARCHAR2(500),
    CONSTRAINT FK_STD_DMN_RQST_COL  FOREIGN KEY (COLUMN_ID) REFERENCES ANALYSIS_COLUMN(COLUMN_ID) ON DELETE CASCADE,
    CONSTRAINT FK_STD_DMN_RQST_DMN  FOREIGN KEY (PROPOSED_DOMAIN_CODE) REFERENCES DOMAIN_CODE(DOMAIN_CODE),
    CONSTRAINT FK_STD_DMN_RQST_REQ  FOREIGN KEY (REQUESTED_BY) REFERENCES APP_USER(USER_ID),
    CONSTRAINT FK_STD_DMN_RQST_RVW  FOREIGN KEY (REVIEWED_BY)  REFERENCES APP_USER(USER_ID),
    CONSTRAINT CK_STD_DMN_RQST_AI   CHECK (AI_SUGGESTED_YN IN ('Y', 'N')),
    CONSTRAINT CK_STD_DMN_RQST_STS  CHECK (REQUEST_STATUS IN ('PENDING', 'APPROVED', 'REJECTED'))
);
COMMENT ON TABLE STANDARD_DOMAIN_REQUEST IS '표준 도메인 확정 신청(신청본 성격) - 담당자 승인 대기열';

CREATE TABLE STANDARD_DOMAIN (
    COLUMN_ID       NUMBER          NOT NULL,
    DOMAIN_CODE     VARCHAR2(20)    NOT NULL,
    VERSION_NO      NUMBER          DEFAULT 1 NOT NULL,
    CONFIRMED_BY    NUMBER          NOT NULL,
    CONFIRMED_AT    TIMESTAMP       DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT PK_STANDARD_DOMAIN PRIMARY KEY (COLUMN_ID),
    CONSTRAINT FK_STANDARD_DOMAIN_COL FOREIGN KEY (COLUMN_ID)   REFERENCES ANALYSIS_COLUMN(COLUMN_ID) ON DELETE CASCADE,
    CONSTRAINT FK_STANDARD_DOMAIN_DMN FOREIGN KEY (DOMAIN_CODE) REFERENCES DOMAIN_CODE(DOMAIN_CODE),
    CONSTRAINT FK_STANDARD_DOMAIN_USR FOREIGN KEY (CONFIRMED_BY) REFERENCES APP_USER(USER_ID)
);
COMMENT ON TABLE STANDARD_DOMAIN IS '승인 완료된 확정 표준 도메인(확정본 성격) - 컬럼당 최신 1건';

