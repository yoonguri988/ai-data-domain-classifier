    CONSTRAINT CK_ANALYSIS_JOB_SCHTYPE CHECK (SCHEDULE_TYPE IN ('ONCE', 'CRON')),
    CONSTRAINT CK_ANALYSIS_JOB_STATUS  CHECK (JOB_STATUS IN ('READY', 'RUNNING', 'SUCCESS', 'FAILED', 'DISABLED'))
