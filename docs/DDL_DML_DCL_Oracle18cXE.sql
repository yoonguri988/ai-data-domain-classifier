-- 2-1. 인증/사용자 (JWT + OAuth2.0 + Redis 세션 대응 영역)
--------------------------------------------------------------------------------

CREATE TABLE APP_USER (
    USER_ID          NUMBER          GENERATED BY DEFAULT AS IDENTITY (START WITH 1000) PRIMARY KEY,
    LOGIN_ID         VARCHAR2(50)    NOT NULL,
    PASSWORD    VARCHAR2(200),                          -- OAuth2 전용 계정은 NULL 허용 (BCrypt 해시 저장)
    USER_NAME        VARCHAR2(100)   NOT NULL,
    EMAIL            VARCHAR2(150)   NOT NULL,
    PHONE_NO         VARCHAR2(20),
    DEPT_NAME        VARCHAR2(100),
    USER_STATUS      VARCHAR2(10)    DEFAULT 'ACTIVE'   NOT NULL,
    LAST_LOGIN_AT    TIMESTAMP,
    CREATED_AT       TIMESTAMP       DEFAULT SYSTIMESTAMP NOT NULL,
    UPDATED_AT       TIMESTAMP       DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT UQ_APP_USER_LOGIN_ID UNIQUE (LOGIN_ID),
    CONSTRAINT UQ_APP_USER_EMAIL    UNIQUE (EMAIL),
    CONSTRAINT CK_APP_USER_STATUS   CHECK (USER_STATUS IN ('ACTIVE', 'LOCKED', 'WITHDRAWN'))
);
COMMENT ON TABLE APP_USER IS '애플리케이션 사용자 계정';

CREATE TABLE APP_ROLE (
    ROLE_ID     NUMBER          GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ROLE_CODE   VARCHAR2(30)    NOT NULL,
    ROLE_NAME   VARCHAR2(100)   NOT NULL,
    CONSTRAINT UQ_APP_ROLE_CODE UNIQUE (ROLE_CODE)
);
COMMENT ON TABLE APP_ROLE IS '권한(Role) 마스터 - Spring Security 인가에 사용';

CREATE TABLE USER_ROLE (
    USER_ID   NUMBER  NOT NULL,
    ROLE_ID   NUMBER  NOT NULL,
    GRANTED_AT TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT PK_USER_ROLE PRIMARY KEY (USER_ID, ROLE_ID),
    CONSTRAINT FK_USER_ROLE_USER FOREIGN KEY (USER_ID) REFERENCES APP_USER(USER_ID) ON DELETE CASCADE,
    CONSTRAINT FK_USER_ROLE_ROLE FOREIGN KEY (ROLE_ID) REFERENCES APP_ROLE(ROLE_ID) ON DELETE CASCADE
);
COMMENT ON TABLE USER_ROLE IS '사용자-권한 매핑(N:M)';

CREATE TABLE OAUTH_ACCOUNT (
    OAUTH_ACCOUNT_ID   NUMBER          GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    USER_ID            NUMBER          NOT NULL,
    PROVIDER           VARCHAR2(20)    NOT NULL,             -- GOOGLE, GITHUB, KAKAO ...
    PROVIDER_USER_ID   VARCHAR2(100)   NOT NULL,
    LINKED_AT          TIMESTAMP       DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT UQ_OAUTH_PROVIDER_USER UNIQUE (PROVIDER, PROVIDER_USER_ID),
    CONSTRAINT FK_OAUTH_ACCOUNT_USER FOREIGN KEY (USER_ID) REFERENCES APP_USER(USER_ID) ON DELETE CASCADE
);
COMMENT ON TABLE OAUTH_ACCOUNT IS 'OAuth2.0 소셜 로그인 연동 계정 (spring-boot-starter-oauth2-client)';

-- Redis가 1차 저장소(TTL 자동만료)이며, 본 테이블은 발급/폐기 감사이력 백업 용도로만 사용한다.
CREATE TABLE REFRESH_TOKEN (
    TOKEN_ID     NUMBER          GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    USER_ID      NUMBER          NOT NULL,
    TOKEN_HASH   VARCHAR2(200)   NOT NULL,                   -- 토큰 원문 대신 SHA-256 해시만 저장
    ISSUED_AT    TIMESTAMP       DEFAULT SYSTIMESTAMP NOT NULL,
    EXPIRES_AT   TIMESTAMP       NOT NULL,
    REVOKED_YN   CHAR(1)         DEFAULT 'N' NOT NULL,
    CLIENT_IP    VARCHAR2(45),
    USER_AGENT   VARCHAR2(300),
    CONSTRAINT CK_REFRESH_TOKEN_REVOKED CHECK (REVOKED_YN IN ('Y', 'N')),
    CONSTRAINT FK_REFRESH_TOKEN_USER FOREIGN KEY (USER_ID) REFERENCES APP_USER(USER_ID) ON DELETE CASCADE
);
COMMENT ON TABLE REFRESH_TOKEN IS 'JWT Refresh Token 발급/폐기 감사이력 (실서비스 TTL은 Redis)';

