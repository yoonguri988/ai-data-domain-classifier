-- 대상 DB    : Oracle Database 18c Express Edition (XE, 무료버전) / PDB명 XEPDB1
-- 파일 구성  : 1) DCL - 테이블스페이스/사용자/권한   2) DDL - 테이블/시퀀스/제약조건
