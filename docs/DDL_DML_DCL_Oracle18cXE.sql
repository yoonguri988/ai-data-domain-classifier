-- 주의       : 본 스크립트는 특정 회사의 실제 운영 스키마가 아닌, 개인 포트폴리오용으로
--             처음부터 새로 설계한 테이블/컬럼명을 사용합니다. (원본 회사 소스코드 미사용)
