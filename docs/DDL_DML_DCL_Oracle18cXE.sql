-- 2-4. AI 도메인 판별 (원본 솔루션의 AI 판별결과 저장 컨셉 재구현) - 외부 AI API 연동 결과
--------------------------------------------------------------------------------

CREATE TABLE DOMAIN_CODE (
    DOMAIN_CODE      VARCHAR2(20)   PRIMARY KEY,             -- ID, AMOUNT, DATE, CONTENT, NAME, NUMBER, COUNT, CONTACT, RATE, CODE, FLAG
    DOMAIN_NAME_KO   VARCHAR2(50)   NOT NULL,
    SORT_ORDER       NUMBER         DEFAULT 0
);
COMMENT ON TABLE DOMAIN_CODE IS '표준 도메인 후보 마스터 (AI 분류 클래스 집합)';

CREATE TABLE DOMAIN_PREDICTION (
    PREDICTION_ID     NUMBER          GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    COLUMN_ID         NUMBER          NOT NULL,
    DOMAIN_CODE       VARCHAR2(20)    NOT NULL,
    PREDICTION_RANK   NUMBER          NOT NULL,              -- 1=가장 유력한 후보
    PROBABILITY       NUMBER(6,5)     NOT NULL,              -- 0.00000 ~ 1.00000
    AI_MODEL_NAME     VARCHAR2(50)    NOT NULL,              -- 예: gpt-4o-mini, claude-haiku, self-hosted-classifier
    AI_MODEL_VERSION  VARCHAR2(20),
    RESPONSE_MS       NUMBER,                                -- 외부 AI API 응답시간(ms) - 성능 개선 지표로 활용
    CACHE_HIT_YN      CHAR(1)         DEFAULT 'N' NOT NULL,  -- Redis 캐시 적중 여부
    PREDICTED_AT      TIMESTAMP       DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT FK_DOMAIN_PREDICTION_COL FOREIGN KEY (COLUMN_ID)   REFERENCES ANALYSIS_COLUMN(COLUMN_ID) ON DELETE CASCADE,
    CONSTRAINT FK_DOMAIN_PREDICTION_DMN FOREIGN KEY (DOMAIN_CODE) REFERENCES DOMAIN_CODE(DOMAIN_CODE),
    CONSTRAINT UQ_DOMAIN_PREDICTION UNIQUE (COLUMN_ID, DOMAIN_CODE),
    CONSTRAINT CK_DOMAIN_PREDICTION_PRB CHECK (PROBABILITY BETWEEN 0 AND 1),
    CONSTRAINT CK_DOMAIN_PREDICTION_CACHE CHECK (CACHE_HIT_YN IN ('Y', 'N'))
);
COMMENT ON TABLE DOMAIN_PREDICTION IS 'AI(외부 API) 기반 컬럼별 표준 도메인 추천 결과 Top-N';

